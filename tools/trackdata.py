#!/usr/bin/env python3 -I
"""Decode how tracks are stored in the ROM and write docs/05-track-storage.md.
Run from the repo root:  python3 -I tools/trackdata.py
Structures (all big-endian, see the doc for the code that reads them):
  $FBC2  course x 9 words: section index per stage            (9 words per course, only the first 3/5/7/9 are used)
  $FB62  24 section records (long pointers)                   -> 5 pointers each: palette A, palette B, road, events, objects
  $FB0E  21 long pointers: curve-shape tables for the $FF0602 event ids 1..21 (ids 11 and 13 are null)
  $8F00  course x 9 stages x 2 longs: tile DMA lists A and B per (course, stage)
  $8E58  Original mode: rival x 3 words (course, stage, c7dc = stage*8)
"""
import os, math
ROM = open(os.path.join(os.getcwd(), "Super Hang-On (World) (En,Ja) (Rev A).md"), "rb").read()
u16 = lambda a: int.from_bytes(ROM[a:a + 2], "big")
s16 = lambda a: int.from_bytes(ROM[a:a + 2], "big", signed=True)
u32 = lambda a: int.from_bytes(ROM[a:a + 4], "big")
LAP = 2048
NAMES = ["MIA FERRARU", "JOSE ALVEREZ", "NOBUHIKO HASEGAWA", "FELICA PEREZ", "HANS BRAUN", "MARIE LEFOURE", "KING ARTHUR"]
LAPS = list(ROM[0xFA92:0xFA92 + 7])
STAGES = [3, 5, 7, 9]

def section_of(course, stage): return u16(0xFBC2 + 2 * (course * 9 + stage))

def road(addr):
    ent = []
    while s16(addr) >= 0:
        ent.append((u16(addr), u16(addr + 2), u16(addr + 4))); addr += 6
    return ent, addr

def events(addr):
    ev = []
    while s16(addr) != 0x7FFF:
        ev.append((u16(addr), u16(addr + 2))); addr += 4
    return ev

def shape(idn):
    p = u32(0xFB0E + 4 * (idn - 1))
    if not p: return None
    ent = []; a = p
    while not (s16(a) == 0 and s16(a + 2) == 0):
        ent.append((s16(a), s16(a + 2))); a += 8
    return p, ent

def lobes(ent):
    """number of separate bends: maximal runs where the direction vector is turned away from straight (x != 0), split by sign"""
    n, sign = 0, 0
    for x, y in ent:
        s = 0 if abs(x) < 120 else (1 if x > 0 else -1)
        if s != 0 and s != sign: n += 1
        if s != 0 or abs(x) < 20: sign = s if s != 0 else 0
    return n

def peak(ent): return max(abs(math.degrees(math.atan2(x, y))) for x, y in ent)

def dma_list(a):
    out = []
    while u16(a): out.append((u16(a), u16(a + 2), u32(a + 4))); a += 8
    return out

def main():
    md = ["# Track storage", "",
          "Generated by `tools/trackdata.py` (checked against the emulator: see the experiment at the end).", ""]
    md += ["## Overview", "",
           "A track is not stored as one blob. The race code gets a **(course, stage)** pair; everything else is looked up from it:", "",
           "```", "(course, stage) --$FBC2--> section 0..23 --$FB62--> section record --> palette A, palette B, road shape, curve events, roadside objects",
           "(course, stage) --$8F00--> tile DMA list A / B  (background / road graphics, plain ROM->VRAM DMA)", "```", "",
           "* `$FF060C` = course (0..3), `$FF060A` = stage (lap counter in Original mode, which is cleared after loading).",
           "* The arcade game has 4 courses with **3, 5, 7 and 9 stages** = 24 sections. Original mode uses 7 of those 24 sections, one per rival; the other 17 are unused there.",
           "* **Original mode picks the track with 3 words per rival** at `$8E58` (course, stage, `$C7DC` = stage x 8, the tile-list cursor). Number of laps is a byte per rival at `$FA92`: " + ", ".join(f"{n}={l}" for n, l in zip(NAMES, LAPS)) + ". Nothing else is rival specific except the bike colour (`$8EF2`).",
           ""]
    md += ["## Original mode: rival -> section", "", "| rival | name | laps | course | stage | section | record | road entries | curves |", "|---:|---|---:|---:|---:|---:|---|---:|---:|"]
    used = {}
    for r in range(7):
        c, s, x = (u16(0x8E58 + 6 * r + 2 * i) for i in range(3))
        sec = section_of(c, s); rec = u32(0xFB62 + 4 * sec)
        ent, _ = road(u32(rec + 8)); used[sec] = r
        md.append(f"| {r} | {NAMES[r]} | {LAPS[r]} | {c} | {s} | {sec} | `${rec:05X}` | {len(ent)} | {sum(1 for e in ent if e[2] != 1)} |")
    md += ["", "## Course layout ($FBC2)", "", "| course | stages | sections in stage order |", "|---:|---:|---|"]
    for c in range(4):
        md.append(f"| {c} | {STAGES[c]} | {', '.join(str(section_of(c, s)) for s in range(STAGES[c]))} |")
    md += ["", "(In the arcade game the stages of a course are driven one after the other; in Original mode a section simply repeats every lap.)", ""]
    md += ["## Section records ($FB62)", "",
           "Each record is 5 long pointers: `+0` palette A (13 words: copied to the CRAM shadow `$D3E0.. / $D396..` and faded in), `+4` palette B (10 words), "
           "`+8` **road shape** (`$FF0672`: entries `(start, radius, state)`, ends with a negative word), `+12` **curve events** (`$FF0602`: `(distance, shape id)` pairs, ends with `$7FFF`), "
           "`+16` **roadside objects** (`$FF066E`, see `tools/roadside.py`). The data of a section sits right after its record, in that order.", "",
           "| section | course.stage | record | road | events | objects | road curves | event list (distance:shape) | used by |", "|---:|---|---|---|---|---|---:|---|---|"]
    owner = {}
    for c in range(4):
        for s in range(STAGES[c]): owner[section_of(c, s)] = f"{c}.{s}"
    for sec in range(24):
        rec = u32(0xFB62 + 4 * sec); rd, ev, ob = u32(rec + 8), u32(rec + 12), u32(rec + 16)
        ent, _ = road(rd)
        e = events(ev)
        md.append(f"| {sec} | {owner.get(sec, '?')} | `${rec:05X}` | `${rd:05X}` | `${ev:05X}` | `${ob:05X}` | {sum(1 for x in ent if x[2] != 1)} | "
                  + " ".join(f"{d}:{i}" for d, i in e) + f" | {('rival %d' % used[sec]) if sec in used else ''} |")
    md += ["", "## Curve events and shape tables ($FB0E)", "",
           "The road you see is not drawn from the physical `(state, radius)` list. A second stream, `$FF0602`, fires **4-5 events per lap** (fetched in the distance routine at `$9E18`, at `$9ED4`, into `$FF061E`; handler at `$F0A2`). "
           "An event id selects a *shape table*: a list of 8-byte entries `(x0, y0, x1, y1)` (4096 = 1.0) that sub_00F0A2 integrates as the bike advances (progress `$FF0738` += distance gain) "
           "to fill the per-scanline curve buffers `$FF1100 / $FF1280` that bend the drawn road. An event runs for 70-150 table steps (about 230-340 distance units) and covers several physical curves, "
           "so one table = one stretch of road (3-5 curves); the physical curve list and the drawn bends are separate data that agree only because the authors made them match. "
           "Entries `(0, 4096, 0, 4096)` are straight road; a table starts with ~20 straight steps, ends with ~10, and a pair `(0, 0)` terminates it.", "",
           "| id | table | steps | bends | max turn (deg) |", "|---:|---|---:|---:|---:|"]
    for i in range(1, 22):
        t = shape(i)
        md.append(f"| {i} | " + (f"`${t[0]:05X}` | {len(t[1])} | {lobes(t[1])} | {peak(t[1]):.0f} |" if t else "(null) | | | |"))
    md += ["", "Sign: negative `x` bends to the right on screen (checked: Felica Perez event id 21 starts on a right curve).", ""]
    md += ["## Tile graphics ($8F00)", "",
           "Per (course, stage) there are two pointers, **list A** (`+0`) and **list B** (`+4`). A list is `(words, VRAM address, ROM source)` triples ending with a zero count (`sub_008C26` for the first load, "
           "`$C5A2` for later ones, executed by the DMA queue at `$F8C0`). The data is plain, uncompressed tile art that is DMAed into VRAM: the first block is always at VRAM `$66E0` (ground / road tiles of the stage), "
           "the next blocks (`$74E0..$9xxx`) are the horizon and sky pieces. The loader counter `$C7DC` advances 4 per load, so the sequence of loads is A(stage), B(stage), A(stage+1), ... "
           "(Original mode rewinds it by 8 once `$3A(a0) == 3`). Many blocks are shared between stages (e.g. `$22464`, `$242E4`, `$28C04`), so the game stores about 20 distinct tile blocks.", "",
           "| course.stage | list A (words @ VRAM <- ROM) | list B |", "|---|---|---|"]
    fmt = lambda l: "<br>".join(f"{n} @ ${v:04X} <- `${p:05X}`" for n, v, p in l)
    for c in range(4):
        for s in range(STAGES[c]):
            o = 0x8F00 + c * 72 + s * 8
            md.append(f"| {c}.{s} | {fmt(dma_list(u32(o)))} | {fmt(dma_list(u32(o + 4)))} |")
    md += ["", "## Experiment: retargeting a rival", "",
           "`tools/patchrom.py` writes a patched ROM (and fixes the boot checksum: the game checks the sum of words `$200..$1A4-end` against `$18E` and hangs otherwise). "
           "Patching only the three words of rival 0 at `$8E58` to `(0, 1, 8)` and to `(1, 4, 32)` and racing rival 0 (`scripts/trackshot.lua`) loads the road shape, events, objects, "
           "palette and tile graphics of course 0 stage 1 (desert, mountains) and course 1 stage 4 (beach) respectively. So **any of the 24 sections can be assigned to any rival by editing 3 words**, "
           "which is all a track randomizer needs. Lap count per rival (`$FA92`) is independent.", "",
           "Open: the unused-in-Original-mode sections were not driven for a full lap (rival 0 stage 1 / 4 only for ~1000 frames, no crash or glitch), the meaning of the A/B lists' trigger, and "
           "the exact end condition `$FF060E` of the event stream.", ""]
    open("docs/05-track-storage.md", "w").write("\n".join(md))
    print("wrote docs/05-track-storage.md")

if __name__ == "__main__": main()
