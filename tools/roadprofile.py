#!/usr/bin/env python3
"""Build the road push profile of a track from SHO_MLOG logs. The push the game applies per tick is 2*(trunc(Dc*v/110)+sign), Dc = trunc(D/64) with D read from the
road buffers at the instant of the call; the logged D is sampled at the end of the frame and is often 0 then, so Dc is recovered from the logged push deltas
($EA7A writes) and speeds instead: for each lap distance d, the integer Dc that explains most observations (no push event = Dc 0).
Usage: tools/roadprofile.py TRACK OUT.lua LOG [LOG...]"""
import sys, collections
sys.path.insert(0, __file__.rsplit('/', 1)[0])
import steermodel as m
def trunc(a, b):
    q = abs(a) // abs(b); return q if (a >= 0) == (b >= 0) else -q
def push_of(dc, v):
    if dc == 0: return 0
    q = trunc(dc * v, 110); return 2 * (q + (1 if q >= 0 else -1))
track, out = sys.argv[1], sys.argv[2]
votes = collections.defaultdict(collections.Counter)
for path in sys.argv[3:]:
    rows = m.parse(path); byk = {r['k']: r for r in rows}
    for k, r in byk.items():
        if k % 3 != 2 or abs(r['lat']) > 480: continue
        pushes = [dl for kk in (k - 2, k - 1, k) if kk in byk for (pc, dl) in byk[kk]['wr'] if pc == 'EA7A']
        v = r['v']; d = r['d'] % 2048
        for dc in range(-14, 15):
            ok = (sum(pushes) == push_of(dc, v)) if pushes else (dc == 0)
            if ok: votes[d][dc] += 1
prof = []
for d in range(2048):
    c = votes.get(d)
    prof.append(c.most_common(1)[0][0] if c else None)
for d in range(2048):
    if prof[d] is None: prof[d] = prof[d - 1] if d else 0
with open(out, 'w') as f:
    f.write(f'-- road push profile of track {track}: Dc per lap distance (push = 2*(trunc(Dc*v/110)+sign)), generated by tools/roadprofile.py\nreturn {{\n')
    for i in range(0, 2048, 32): f.write(' ' + ','.join(str(x) for x in prof[i:i + 32]) + ',\n')
    f.write('}\n')
amb = sum(1 for d in range(2048) if d in votes and len(votes[d]) > 1 and votes[d].most_common(2)[0][1] == votes[d].most_common(2)[1][1])
print(f'track {track}: {len(votes)} distances sampled, {amb} ambiguous, nonzero {sum(1 for x in prof if x)}')
