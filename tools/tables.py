#!/usr/bin/env python3 -I
"""Generate docs/03-original-mode-tables.md from the ROM:  python3 -I tools/tables.py [ROM]
(rivals, sponsors/payouts, mechanics, parts catalogue, all speech). Money in the ROM is BCD in units of $100."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import msgs
ROM = sys.argv[1] if len(sys.argv) > 1 else "Super Hang-On (World) (En,Ja) (Rev A).md"
r = open(ROM, "rb").read(); u32 = msgs.u32; u16 = msgs.u16
bcd = lambda b: int(b.hex())
money = lambda n: "$" + format(n * 100, ",")
rivals = ["MIA FERRARU", "JOSE ALVEREZ", "NOBUHIKO HASEGAWA", "FELICA PEREZ", "HANS BRAUN", "MARIE LEFOURE", "KING ARTHUR"]
mech = ["RICARDO MONTOYA", "MIKI AISAWA", "KOUTARO KITA", "TAKESHI ONDA", "TOM JONES", "SONNYA ILLVICH", "MICKEY WEI"]
spons = ["PHARMACY", "PIZZA CHAIN STORE", "APPLIANCE STORE", "GAME COMPANY", "DISTRIBUTOR", "BIKE MANUFACTURER", "GIANT OIL COMPANY"]
o = []; P = o.append
P("# Original mode – data tables (generated by `python3 -I tools/tables.py`; all values read from the ROM)\n")
P("Money in the ROM is packed BCD in units of $100; the tables below are already multiplied (display values).\n")
P("## Rivals (index = `$FFB606`)\n")
P("| # | rival | laps | base lap time (BCD long at $8D84+4n) | sponsor (same index) |")
P("|---|---|---|---|---|")
for i in range(7):
    t = r[0x8D84 + 4*i:0x8D84 + 4*i + 4]
    P("| %d | %s | %d | %d'%02d\"%02d (+0.30..0.66 random per lap) | %s |" % (i, rivals[i], u16(r, 0xC3C4 + 2*i) + 1, int(t[1:2].hex()), int(t[2:3].hex()), int(t[3:4].hex()), spons[i]))
P("\n## Sponsors: payout after a race (table at $157C0, 16 bytes per sponsor)\n")
P("| sponsor | win | lose narrowly | lose clearly |"); P("|---|---|---|---|")
for i in range(7):
    row = r[0x157C0 + 16*i:0x157C0 + 16*i + 16]
    P("| %s | %s | %s | %s |" % (spons[i], money(bcd(row[0:4])), money(bcd(row[4:8])), money(bcd(row[8:12]))))
P("\n## Mechanics (index = `$FFB60A` / `$FFB60E`), hire price (table $1563E)\n")
P("| # | mechanic | price | roll mask | P(+1 repair, else -1) |"); P("|---|---|---|---|---|")
masks = [0x80, 0xC0, 0xE0, 0xF0, 0xF8, 0xFC, 0xFE]
for i in range(7):
    nb = bin(masks[i]).count("1")
    P("| %d | %s | %s | $%02X | %d/%d |" % (i, mech[i], money(bcd(r[0x1563E + 4*i:0x1563E + 4*i + 4])), masks[i], (1 << nb) - 1, 1 << nb))
P("\nMechanic phrases by category (`$` table $11D40 + mechanic*4 + category*32; the part name is overlaid in red in the blank gap):\n")
for cat in range(4):
    P("**category %d**\n" % cat)
    for m in range(7):
        P("- %s: %s" % (mech[m], " / ".join(x.strip() for x in msgs.block(r, u32(r, 0x11D40 + m*4 + cat*32)))))
    P("")
P("## Parts catalogue (prices: table $1565E, 8 longs per slot)\n")
names = {0: ["IRON CRADLE", "DOUBLE CRADLE", "ALUMINIUM DOUBLE CRADLE", "ALUMINIUM SPACE", "TITANIUM SPACE", "TITANIUM MONO-COQUE"],
 1: ["OHC NORMAL", "DOHC NORMAL", "DOHC V4", "TURBO V4", "CERAMIC TURBO", "TWIN TURBO"],
 2: ["DRUM", "DISC", "VENTILATED DISC", "DOUBLE DISC", "ANTI-SKID"],
 3: ["NORMAL", "COL", "WORKS ORIGINAL", "PRIVATE ORIGINAL"],
 4: ["REGULAR", "MANUAL", "TOP", "PRIVATE ORIGINAL"],
 5: ["NORMAL", "RADIAL", "HIGH PERFORMANCE", "SLICK", "ORIGINAL SLICK"]}
for s, sl in enumerate(["FRAME", "ENGINE", "BRAKE", "MUFFLER", "OIL", "TIRE"]):
    P("**%s** (slot %d: tier at $FFB618+2s, health at $FFB648+2s)\n" % (sl, s))
    for t, n in enumerate(names[s]):
        P("- tier %d: %s – %s" % (t, n, money(bcd(r[0x1565E + 32*s + 4*t:0x1565E + 32*s + 4*t + 4]))))
    P("")
P("## Rival speech ($10FE2 + rival*4 + state*32; state 0 before the race, 1 after beating the rival's time by a lot... see doc 02)\n")
for st in range(4):
    P("**state %d**\n" % st)
    for rv in range(7):
        P("- %s: %s" % (rivals[rv], " / ".join(x.strip() for x in msgs.block(r, u32(r, 0x10FE2 + rv*4 + st*32)))))
    P("")
P("## Sponsor speech ($13298 + sponsor*4 + state*32; state 0 intro, 1 lost clearly, 2 lost narrowly, 3 won, 4 five wins)\n")
for st in range(5):
    P("**state %d**\n" % st)
    for s in range(7):
        P("- %s: %s" % (spons[s], " / ".join(x.strip() for x in msgs.block(r, u32(r, 0x13298 + s*4 + st*32)))))
    P("")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "03-original-mode-tables.md"), "w").write("\n".join(o))
