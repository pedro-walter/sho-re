#!/usr/bin/env python3 -I
"""Decode the road-shape stream ($FF0672) of the 7 Original-mode tracks and print / write docs/04-track-data.md.
Entry = 3 words: start distance, radius, state (1 straight, 2 left-hand curve, 3 right-hand curve); terminated by a negative word.
A segment lasts until the next entry (the last one until 2048, the lap length). Distance gain while driving a curve
is scaled by (radius + side/40)/radius, side = lateral offset toward the inside ($9E18)."""
import os, sys
ROOT = os.getcwd()
ROM = open(os.path.join(ROOT, "Super Hang-On (World) (En,Ja) (Rev A).md"), "rb").read()
u16 = lambda a: int.from_bytes(ROM[a:a+2], "big")
# rival index -> (name, laps, $FF0672 stream address, $FF0602 stream address)
TRACKS = [(0, "MIA FERRARU", 2, 0x560CA, 0x56156), (1, "JOSE ALVEREZ", 2, 0x56BF0, 0x56C88), (2, "NOBUHIKO HASEGAWA", 3, 0x5700A, 0x57066),
          (3, "FELICA PEREZ", 3, 0x553F2, 0x554C6), (4, "HANS BRAUN", 4, 0x55E70, 0x55F08), (5, "MARIE LEFOURE", 5, 0x55696, 0x55728),
          (6, "KING ARTHUR", 6, 0x55CA6, 0x55D20)]
LAP = 2048
DIR = {1: "straight", 2: "left", 3: "right"}

def segments(addr):
    ent = []
    while u16(addr) < 0x8000:
        ent.append((u16(addr), u16(addr + 2), u16(addr + 4))); addr += 6
    seg = [(0, ent[0][0], 0, 1)] if ent and ent[0][0] else []
    for i, (s, r, st) in enumerate(ent):
        e = ent[i + 1][0] if i + 1 < len(ent) else LAP
        seg.append((s, e, r, st))
    return seg

def strip(seg, n=64):
    out = ""
    for k in range(n):
        d = k * LAP // n
        c = "."
        for s, e, r, st in seg:
            if s <= d < e: c = {1: ".", 2: "<", 3: ">"}[st]
        out += c
    return out

if __name__ == "__main__":
    md = ["# Track data – road shape (curves)", "",
          "Generated by `tools/roadcurves.py`. The road shape of each Original-mode track is one list per lap (the same list repeats every lap, a lap is 2048 distance units).",
          "Entry = start distance, radius, state. State 1 = straight (radius word is 0), 2 = left-hand curve, 3 = right-hand curve",
          "(3: the bike drifts toward negative lateral positions, i.e. outward to the left → right-hand curve **[exp]**).",
          "The distance gain per frame in a curve is multiplied by `(radius + inside_offset/40) / radius` (see `docs/02-original-mode.md` §8), so a **smaller radius** = a sharper curve = a bigger reward for the inside line.",
          "Road half-width ≈ 270 lateral units → the extreme inside line gains `6/radius` (the game divides by 40 with truncation; ≈ 6 % at radius 100, ≈ 18 % at radius 38).", "",
          "Strip legend: `.` straight, `<` left-hand curve, `>` right-hand curve; one character = 32 distance units, a lap = 64 characters.", ""]
    for r, name, laps, a, _ in TRACKS:
        seg = segments(a)
        cur = [x for x in seg if x[3] != 1]
        md += ["## Rival %d – %s (%d laps)" % (r, name, laps), "", "Stream at `$%06X`; `%s`" % (a, strip(seg)), "",
               "| from | to | state | radius | inside-line gain at 270 |", "|---:|---:|---|---:|---:|"]
        for s, e, rad, st in seg:
            if st == 1: md.append("| %d | %d | straight | – | – |" % (s, e))
            else: md.append("| %d | %d | %s | %d | %.1f %% |" % (s, e, DIR[st], rad, 100 * (270 // 40) / rad))
        tot = sum(e - s for s, e, rad, st in cur)
        md += ["", "Curves: %d segments covering %d of %d units (%.0f %% of the lap); sharpest radius %d." % (len(cur), tot, LAP, 100 * tot / LAP, min(x[2] for x in cur)), ""]
    open(os.path.join(ROOT, "docs/04-track-data.md"), "w").write("\n".join(md))
    print("\n".join(md[9:40]))
